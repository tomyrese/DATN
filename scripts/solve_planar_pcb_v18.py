import math

# Import pad positions
from solve_planar_pcb_v3 import (
    pi_odd, pi_even, tb1, tb2, m1, m2, m3, m4,
    tcrt, us1, us2, r1, r2, r3, r4, oled
)

# Physical pad positions for R3 and R4 from bak
# R3 at (120.9349, 61.4360) rotated 180:
r3_pad1_us2_echo = (124.7449, 61.4360) # Pad 1: Net-(U_US2-ECHO)
r3_pad2_echo_r = (117.1249, 61.4360)   # Pad 2: /ECHO_R

# R4 at (120.97, 65.4452) angle 0:
r4_pad1_echo_r = (117.1600, 65.4452)   # Pad 1: /ECHO_R
r4_pad2_gnd = (124.7800, 65.4452)      # Pad 2: GND

paths = []

def add(net, pts, width=0.6):
    for i in range(len(pts) - 1):
        paths.append({
            'net': net,
            'p1': pts[i],
            'p2': pts[i+1],
            'width': width
        })

def build_v18_routing():
    paths.clear()

    # ==========================================================================
    # 1. TB6612 LEFT INTERNAL ARCHES (Y in [62, 70])
    # ==========================================================================
    add("/AIN1_L", [tb1[3], (63.88, 64.5), (68.96, 64.5), tb1[5]])
    add("/AIN2_L", [tb1[2], (61.34, 66.5), (71.50, 66.5), tb1[6]])
    add("/PWMA_L", [tb1[1], (58.80, 68.5), (74.04, 68.5), tb1[7]])
    add("GND", [tb1[8], tb1[16]])
    add("GND", [tb1[11], (63.88, 73.0), (76.58, 73.0)])

    # ==========================================================================
    # 2. TB6612 LEFT MOTORS (Outer Left Channel X in [51, 57])
    # ==========================================================================
    add("/M1_A", [tb1[12], (66.42, 78.5), (56.5, 78.5), (56.5, 53.4005), m1[1]], width=0.8)
    add("/M1_B", [tb1[13], (68.96, 80.0), (55.0, 80.0), (55.0, 51.50), (68.948, 51.50), m1[2]], width=0.8)
    add("/M2_B", [tb1[14], (71.50, 81.5), (53.5, 81.5), (53.5, 49.50), (75.53, 49.50), m2[1]], width=0.8)
    add("/M2_A", [tb1[15], (74.04, 83.0), (52.0, 83.0), (52.0, 48.00), (78.07, 48.00), m2[2]], width=0.8)

    # ==========================================================================
    # 3. TB6612 LEFT CONTROL EXITS TO PI 4 (Concentric Nested Arches)
    # Pad 7 (PWMA) -> Pin 37 (innermost, Y=59.0)
    # Pad 6 (AIN2) -> Pin 35 (middle, Y=57.5)
    # Pad 5 (AIN1) -> Pin 33 (outermost, Y=56.0)
    # ==========================================================================
    add("/PWMA_L", [tb1[7], (74.04, 59.0), (81.60, 59.0), pi_odd(37)])
    add("/AIN2_L", [tb1[6], (71.50, 57.5), (84.14, 57.5), pi_odd(35)])
    add("/AIN1_L", [tb1[5], (68.96, 56.0), (86.68, 56.0), pi_odd(33)])

    # ==========================================================================
    # 4. TB6612 RIGHT INTERNAL ARCHES (Y in [62, 70])
    # ==========================================================================
    add("/AIN1_R", [tb2[3], (136.88, 64.5), (141.96, 64.5), tb2[5]])
    add("/AIN2_R", [tb2[2], (134.34, 66.5), (144.50, 66.5), tb2[6]])
    add("/PWMA_R", [tb2[1], (131.80, 68.5), (147.04, 68.5), tb2[7]])
    add("GND", [tb2[8], tb2[16]])
    add("GND", [tb2[11], (136.88, 73.0), (149.58, 73.0)])

    # ==========================================================================
    # 5. TB6612 RIGHT MOTORS (All 4 in East Channel X in [152, 158])
    # ==========================================================================
    add("/M4_A", [tb2[15], (147.04, 78.5), (152.07, 78.5), m4[2]], width=0.8)
    add("/M4_B", [tb2[14], (144.50, 80.0), (154.5, 80.0), (154.5, 51.50), (149.53, 51.50), m4[1]], width=0.8)
    add("/M3_B", [tb2[13], (141.96, 81.5), (156.0, 81.5), (156.0, 49.50), (141.07, 49.50), m3[2]], width=0.8)
    add("/M3_A", [tb2[12], (139.42, 83.0), (157.5, 83.0), (157.5, 48.00), (138.53, 48.00), m3[1]], width=0.8)

    # ==========================================================================
    # 6. TB6612 RIGHT CONTROL EXITS TO PI 4 (Via West corridor X in [126.5, 129.5])
    # Pad 1 (PWMA) -> (131.8, 68.5) -> (126.5, 68.5) -> (126.5, 82.0) -> (124.78, 82.0) -> Pin 3
    # Pad 2 (AIN2) -> (134.34, 66.5) -> (128.0, 66.5) -> (128.0, 84.0) -> (122.24, 84.0) -> Pin 5
    # Pad 3 (AIN1) -> (136.88, 64.5) -> (129.5, 64.5) -> (129.5, 86.0) -> (119.70, 86.0) -> Pin 7
    # ==========================================================================
    add("/PWMA_R", [(131.80, 68.5), (126.50, 68.5), (126.50, 82.0), (124.78, 82.0), pi_odd(3)])
    add("/AIN2_R", [(134.34, 66.5), (128.00, 66.5), (128.00, 84.0), (122.24, 84.0), pi_odd(5)])
    add("/AIN1_R", [(136.88, 64.5), (129.50, 64.5), (129.50, 86.0), (119.70, 86.0), pi_odd(7)])

    # ==========================================================================
    # 7. TCRT5000 SENSORS (Parallel straight vertical tracks)
    # ==========================================================================
    add("/LINE_R", [tcrt[5], pi_odd(23)])
    add("/LINE_C", [tcrt[4], pi_odd(21)])
    add("/LINE_L", [tcrt[3], pi_odd(19)])
    add("/+3V3_LOGIC", [tcrt[2], pi_odd(17)])

    # ==========================================================================
    # 8. ULTRASONIC SENSORS & VOLTAGE DIVIDERS
    # ==========================================================================
    # Left Ultrasonic:
    add("/TRIG_L", [us1[2], (88.92, 53.0), (87.60, 53.0), (87.60, 91.0), (89.22, 91.0), pi_odd(31)], width=0.4)
    add("Net-(U_US1-ECHO)", [us1[3], (91.46, 63.0), (89.22, 63.0), r1[1]])
    add("/ECHO_L", [r1[2], (96.84, 69.00), r2[1]])
    add("/ECHO_L", [r2[1], (96.80, 75.0), (91.76, 75.0), pi_odd(29)])
    
    # Left top GND:
    add("GND", [r2[2], (89.18, 74.00), (94.00, 74.00), us1[4]])
    add("GND", [us1[4], (94.00, 48.00), (109.54, 48.00), tcrt[1]])

    # Top GND jumper JMP12 from (94.00, 73.50) to (91.76, 99.00) on bottom trunk:
    add("GND", [(94.00, 74.00), (94.00, 73.50)])
    add("GND", [(91.76, 99.00), pi_even(30)])

    # Right Ultrasonic:
    # TRIG_R to Pin 15:
    add("/TRIG_R", [us2[2], (117.1459, 53.0), (109.54, 53.0), pi_odd(15)])
    
    # Net-(U_US2-ECHO) connects US2 Echo to R3 Pad 1:
    add("Net-(U_US2-ECHO)", [us2[3], (119.6859, 54.0), (124.7449, 54.0), r3_pad1_us2_echo])
    
    # ECHO_R connects R3 Pad 2 (117.1249) to R4 Pad 1 (117.16) and to JMP7 via at (117.16, 68.0):
    add("/ECHO_R", [r3_pad2_echo_r, (117.1600, 61.4360), r4_pad1_echo_r, (117.1600, 68.00)])
    # JMP7 Echo_R via (112.08, 88.00) to Pi Pin 13:
    add("/ECHO_R", [(112.08, 88.00), pi_odd(13)])

    # Right top GND:
    # US2 Pad 4 is at (122.2259, 50.5138)
    # Connect TCRT Pad 1 (109.54, 48.0) across to US2 Pad 4:
    add("GND", [(109.54, 48.00), (122.2259, 48.00), us2[4]])
    
    # R4 Pad 2 (GND) is at (124.78, 65.4452):
    # Connect R4 Pad 2 to Pi Pin 9 (GND at 117.16, 93.5575) via jumper JMP13
    # JMP13 via at (124.78, 68.00) to (117.16, 90.00) -> Pin 9:
    add("GND", [r4_pad2_gnd, (124.78, 68.00)])
    add("GND", [(117.16, 90.00), pi_odd(9)])

    # ==========================================================================
    # 9. GROUND TRUNK ALONG Y = 101.50
    # ==========================================================================
    trunk_gnd_y = 101.50
    # Pin 39 routes around West end of Pi header:
    add("GND", [pi_odd(39), (77.00, 93.5575), (77.00, trunk_gnd_y), (79.06, trunk_gnd_y)])
    add("GND", [pi_even(34), (86.68, trunk_gnd_y)])
    add("GND", [pi_even(30), (91.76, trunk_gnd_y)])
    
    # Pin 25 routes via jumper JMP9 over Pi socket:
    add("GND", [pi_odd(25), (96.84, 89.00)])
    add("GND", [(96.84, 99.00), (96.84, trunk_gnd_y)])
    
    add("GND", [pi_even(20), (104.46, trunk_gnd_y)])
    add("GND", [pi_even(14), (112.08, trunk_gnd_y)])
    add("GND", [pi_even(6), (122.24, trunk_gnd_y)])
    add("GND", [(77.00, trunk_gnd_y), (149.58, trunk_gnd_y)])

    # Pin 40 grounded locally to trunk:
    add("GND", [pi_even(40), (79.06, trunk_gnd_y)])

    # JMP8 GND_R connects bottom trunk to East TB6612 GND:
    add("GND", [(149.58, trunk_gnd_y), (149.58, 90.00)]) # JMP8 south via
    add("GND", [(149.58, 69.00), tb2[8]])                 # JMP8 north via to TB6612 Pad 8

    # ==========================================================================
    # 10. +5V POWER BUS (Y = 105.00, West channel X = 50.50, Top rail Y = 43.50)
    # ==========================================================================
    bus_5v_y = 105.00
    west_5v_x = 50.50
    top_5v_y = 43.50

    # Pi 5V Pins 2 and 4 drop South to 5V bus:
    add("/+5V_PWR", [pi_even(2), (127.32, bus_5v_y)], width=0.8)
    add("/+5V_PWR", [pi_even(4), (124.78, bus_5v_y)], width=0.8)
    
    # Bus extends West around Pi header and up West edge:
    add("/+5V_PWR", [(127.32, bus_5v_y), (west_5v_x, bus_5v_y), (west_5v_x, top_5v_y), (114.6059, top_5v_y)], width=0.8)
    
    # Top 5V rail drops to US1 Pad 1 and US2 Pad 1:
    add("/+5V_PWR", [(86.38, top_5v_y), us1[1]])
    add("/+5V_PWR", [(114.6059, top_5v_y), us2[1]])

    # TB6612 Left VCC: JMP10 via at (61.34, 43.50) to (61.34, 74.00) -> Pad 10
    add("/+5V_PWR", [(61.34, 74.00), tb1[10]])

    # TB6612 Right VCC: JMP11 via at (127.32, 99.00) to (134.34, 74.00) -> Pad 10
    add("/+5V_PWR", [pi_even(2), (127.32, 99.00)])
    add("/+5V_PWR", [(134.34, 74.00), tb2[10]])

    # ==========================================================================
    # 11. MOTOR VOLTAGE (VM_MOTOR)
    # ==========================================================================
    # JMP6_VM: via at (58.80, 74.00) to (131.80, 74.00)
    add("/VM_MOTOR", [tb1[9], (58.80, 74.00)], width=1.0)
    add("/VM_MOTOR", [(131.80, 74.00), tb2[9]], width=1.0)

    # ==========================================================================
    # 12. I2C BUS (OLED & EXPANSION)
    # ==========================================================================
    # SDA: Pin 27 -> JMP1 via at (94.30, 87.0) -> (144.50, 87.0) -> OLED Pad 4
    add("/I2C_SDA", [pi_odd(27), (94.30, 87.00)])
    add("/I2C_SDA", [(144.50, 87.00), oled[4]])

    # SCL: Pin 28 -> JMP2 via at (94.30, 99.0) -> (147.04, 99.0) -> OLED Pad 3
    add("/I2C_SCL", [pi_even(28), (94.30, 99.00)])
    add("/I2C_SCL", [(147.04, 99.00), oled[3]])

    # OLED Power:
    add("GND", [oled[2], (149.58, trunk_gnd_y)])
    add("/+3V3_LOGIC", [oled[1], (152.12, 88.00)])
    add("/+3V3_LOGIC", [pi_odd(17), (107.00, 84.00)])

    # ==========================================================================
    # 13. MOTOR DRIVER STANDBY PINS (STBY_L & STBY_R)
    # ==========================================================================
    # Left Standby: Pad 4 (66.42, 61.2075) -> JMP4 via (66.42, 58.0) -> (81.60, 99.0) -> Pin 38
    add("/STBY_L", [tb1[4], (66.42, 58.00)])
    add("/STBY_L", [(81.60, 99.00), pi_even(38)])

    # Right Standby: Pad 4 (139.42, 61.2075) -> JMP5 via (139.42, 58.0) -> (114.62, 85.0) -> Pin 11
    add("/STBY_R", [tb2[4], (139.42, 58.00)])
    add("/STBY_R", [(114.62, 85.00), pi_odd(11)])

build_v18_routing()
print(f"Total track segments in v18: {len(paths)}")

