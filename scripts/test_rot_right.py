import math

fp_x, fp_y = 140.69, 68.8275

for rot in [90.0, 270.0]:
    rad = math.radians(rot)
    pads = {
        1: (-7.62, -8.89), 2: (-7.62, -6.35), 3: (-7.62, -3.81), 4: (-7.62, -1.27),
        5: (-7.62, 1.27), 6: (-7.62, 3.81), 7: (-7.62, 6.35), 8: (-7.62, 8.89),
        9: (7.62, -8.89), 10: (7.62, -6.35), 11: (7.62, -3.81), 12: (7.62, -1.27),
        13: (7.62, 1.27), 14: (7.62, 3.81), 15: (7.62, 6.35), 16: (7.62, 8.89),
    }
    print(f"\nRIGHT when rot = {rot}:")
    for p in [9, 10, 11, 12, 13, 14, 15, 16, 1, 2, 3, 4, 5, 6, 7, 8]:
        lx, ly = pads[p]
        wx = fp_x + lx * math.cos(rad) - ly * math.sin(rad)
        wy = fp_y + lx * math.sin(rad) + ly * math.cos(rad)
        print(f"  Pad {p:>2}: world ({wx:.2f}, {wy:.2f})")

