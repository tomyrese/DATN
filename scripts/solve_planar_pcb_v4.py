from test_routing_engine import test_routing
from solve_planar_pcb_v3 import (
    pi_odd, pi_even, tb1, tb2, m1, m2, m3, m4,
    tcrt, us1, us2, r1, r2, r3, r4, oled
)

def route_v4(add):
    # ==========================================================================
    # 1. TB6612 LEFT INTERNAL ARCHES (Y in [62, 70])
    # ==========================================================================
    add("/AIN1_L", [tb1[3], (63.88, 64.5), (68.96, 64.5), tb1[5]])
    add("/AIN2_L", [tb1[2], (61.34, 66.5), (71.50, 66.5), tb1[6]])
    add("/PWMA_L", [tb1[1], (58.80, 68.5), (74.04, 68.5), tb1[7]])
    add("GND", [tb1[8], tb1[16]])
    add("GND", [tb1[11], (63.88, 73.0), (76.58, 73.0)])

    # ==========================================================================
    # 2. TB6612 LEFT MOTORS (ALL ROUTED AROUND LEFT MARGIN X in [52, 57])
    # No motor tracks on the right of TB6612!
    # ==========================================================================
    # MOTOR1 (Front-Left):
    add("/M1_A", [tb1[12], (66.42, 78.5), (56.0, 78.5), (56.0, 53.4005), m1[1]], width=0.8)
    add("/M1_B", [tb1[13], (68.96, 80.0), (54.5, 80.0), (54.5, 51.50), (68.948, 51.50), m1[2]], width=0.8)

    # MOTOR2 (Rear-Left):
    # Pad 14 (BO2) and Pad 15 (BO1) also route left around the margin!
    add("/M2_B", [tb1[14], (71.50, 81.5), (53.0, 81.5), (53.0, 49.50), (75.53, 49.50), m2[1]], width=0.8)
    add("/M2_A", [tb1[15], (74.04, 83.0), (51.5, 83.0), (51.5, 48.00), (78.07, 48.00), m2[2]], width=0.8)

    # ==========================================================================
    # 3. TB6612 LEFT CONTROL EXITS TO PI 4 (Completely clear on the right!)
    # ==========================================================================
    add("/PWMA_L", [tb1[7], (74.04, 59.0), (86.68, 59.0), pi_odd(33)])
    add("/AIN2_L", [tb1[6], (71.50, 58.0), (84.14, 58.0), pi_odd(35)])
    add("/AIN1_L", [tb1[5], (68.96, 57.0), (81.60, 57.0), pi_odd(37)])

    # ==========================================================================
    # 4. TB6612 RIGHT INTERNAL ARCHES (Y in [62, 70])
    # ==========================================================================
    add("/AIN1_R", [tb2[3], (136.88, 64.5), (141.96, 64.5), tb2[5]])
    add("/AIN2_R", [tb2[2], (134.34, 66.5), (144.50, 66.5), tb2[6]])
    add("/PWMA_R", [tb2[1], (131.80, 68.5), (147.04, 68.5), tb2[7]])
    add("GND", [tb2[8], tb2[16]])
    add("GND", [tb2[11], (136.88, 73.0), (149.58, 73.0)])

    # ==========================================================================
    # 5. TB6612 RIGHT MOTORS (ALL ROUTED AROUND RIGHT MARGIN X in [153, 158])
    # ==========================================================================
    # MOTOR4 (Rear-Right):
    add("/M4_B", [tb2[14], (144.50, 78.5), (153.5, 78.5), (153.5, 51.50), (149.53, 51.50), m4[1]], width=0.8)
    add("/M4_A", [tb2[15], (147.04, 80.0), (155.0, 80.0), (155.0, 53.9425), m4[2]], width=0.8)

    # MOTOR3 (Front-Right): routes around outer right margin as well!
    add("/M3_A", [tb2[12], (139.42, 81.5), (156.5, 81.5), (156.5, 49.50), (138.53, 49.50), m3[1]], width=0.8)
    add("/M3_B", [tb2[13], (141.96, 83.0), (158.0, 83.0), (158.0, 48.00), (141.07, 48.00), m3[2]], width=0.8)

    # ==========================================================================
    # 6. TB6612 RIGHT CONTROL EXITS TO PI 4 (Exiting North cleanly)
    # ==========================================================================
    add("/PWMA_R", [tb2[1], (131.80, 59.0), (124.78, 59.0), pi_odd(3)])
    add("/AIN2_R", [tb2[2], (134.34, 58.0), (122.24, 58.0), pi_odd(5)])
    add("/AIN1_R", [tb2[3], (136.88, 57.0), (119.70, 57.0), pi_odd(7)])

    # ==========================================================================
    # 7. TCRT5000 SENSORS (Parallel straight vertical tracks)
    # ==========================================================================
    add("/LINE_R", [tcrt[5], pi_odd(23)])
    add("/LINE_C", [tcrt[4], pi_odd(21)])
    add("/LINE_L", [tcrt[3], pi_odd(19)])
    add("/+3V3_LOGIC", [tcrt[2], pi_odd(17)])

    # ==========================================================================
    # 8. ULTRASONIC SENSORS & VOLTAGE DIVIDERS
    # ==========================================================================
    # Left Ultrasonic:
    add("/TRIG_L", [us1[2], (88.92, 53.0), (88.0, 53.0), (88.0, 91.0), (89.22, 91.0), pi_odd(31)])
    add("Net-(U_US1-ECHO)", [us1[3], (91.46, 63.0), (89.22, 63.0), r1[1]])
    add("/ECHO_L", [r1[2], (96.84, 69.0), (96.80, 69.0), r2[1]])
    add("/ECHO_L", [r2[1], (96.80, 75.0), (91.76, 75.0), pi_odd(29)])
    add("GND", [r2[2], (89.18, 74.0), (94.0, 74.0), us1[4]])

    # Right Ultrasonic:
    add("/TRIG_R", [us2[2], (117.1459, 53.0), (109.54, 53.0), pi_odd(15)])
    add("Net-(U_US2-ECHO)", [us2[3], (119.6859, 55.0), (117.12, 55.0), r3[1]])
    add("/ECHO_R", [r3[2], (124.7449, 63.5), (124.78, 63.5), r4[2]])
    add("/ECHO_R", [r4[2], (124.78, 68.0), (112.08, 68.0), pi_odd(13)])
    add("GND", [r4[1], pi_odd(9)])

    # Top Sensor Ground connecting us1, tcrt, us2
    add("GND", [us1[4], (94.0, 46.50), (109.54, 46.50), tcrt[1]])
    add("GND", [tcrt[1], (109.54, 46.50), (122.2259, 46.50), us2[4]])

    # ==========================================================================
    # 9. GROUND TRUNK ALONG Y = 101.50
    # ==========================================================================
    trunk_gnd_y = 101.50
    add("GND", [pi_odd(39), (79.06, trunk_gnd_y)])
    add("GND", [pi_even(34), (86.68, trunk_gnd_y)])
    add("GND", [pi_even(30), (91.76, trunk_gnd_y)])
    add("GND", [pi_odd(25), (96.84, trunk_gnd_y)])
    add("GND", [pi_even(20), (104.46, trunk_gnd_y)])
    add("GND", [pi_even(14), (112.08, trunk_gnd_y)])
    add("GND", [pi_even(6), (122.24, trunk_gnd_y)])
    # Trunk stops at 122.24 so +5V at 127.32 drops freely!
    add("GND", [(76.58, trunk_gnd_y), (122.24, trunk_gnd_y)], width=1.2)

    # Connect Left TB6612 Pad 16 down to GND trunk
    add("GND", [tb1[16], (76.58, trunk_gnd_y)])
    # Connect Left Pad 8 up to Top Sensor GND
    add("GND", [tb1[8], (76.58, 46.50), (94.0, 46.50)])

    # Right side GND: connects tb2[16] and oled[2]
    add("GND", [tb2[16], (149.58, 96.50), oled[2]])
    # Connect tb2[8] up to Top Sensor GND
    add("GND", [tb2[8], (149.58, 46.50), (122.2259, 46.50)])

    # ==========================================================================
    # 10. +5V_PWR BUS
    # ==========================================================================
    trunk_5v_y = 105.00
    add("/+5V_PWR", [pi_even(4), pi_even(2)], width=1.2)
    # Drops from pi_even(2) at X=127.32 to trunk_5v_y (completely right of 122.24 GND trunk!)
    add("/+5V_PWR", [pi_even(2), (127.32, trunk_5v_y), (50.00, trunk_5v_y), (50.00, 43.50), (86.38, 43.50), us1[1]], width=1.2)
    add("/+5V_PWR", [(86.38, 43.50), (114.6059, 43.50), us2[1]], width=1.2)
    add("/+5V_PWR", [tb1[10], (61.34, 85.0), (50.00, 85.0)], width=1.0)
    add("/+5V_PWR", [tb2[10], (134.34, 85.0), (159.5, 85.0), (159.5, trunk_5v_y), (127.32, trunk_5v_y)], width=1.0)

    # ==========================================================================
    # 11. TOP WIRE JUMPERS TRACKS
    # ==========================================================================
    # JMP1: SDA
    add("/I2C_SDA", [pi_odd(27), (94.30, 87.00)])
    add("/I2C_SDA", [(144.50, 87.00), oled[4]])

    # JMP2: SCL (exits South from Pi header)
    add("/I2C_SCL", [pi_even(28), (94.30, 99.00)])
    add("/I2C_SCL", [(147.04, 99.00), oled[3]])

    # JMP3: 3V3
    add("/+3V3_LOGIC", [pi_odd(17), (107.00, 84.00)])
    add("/+3V3_LOGIC", [(152.12, 84.00), oled[1]])

    # JMP4: STBY_L
    add("/STBY_L", [tb1[4], (66.42, 63.00)])
    add("/STBY_L", [(81.60, 84.00), pi_even(38)])

    # JMP5: STBY_R
    add("/STBY_R", [tb2[4], (139.42, 63.00)])
    add("/STBY_R", [(114.62, 85.00), pi_odd(11)])

    # JMP6: VM_MOTOR
    add("/VM_MOTOR", [tb1[9], (58.80, 74.00)], width=1.2)
    add("/VM_MOTOR", [tb2[9], (131.80, 74.00)], width=1.2)

num_conflicts, paths = test_routing(route_v4)
